"""Training entry point for the reusable sprint ML model."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict

import pandas as pd

from drone_analysis.ml.features import DEFAULT_FEATURE_COLUMNS
from drone_analysis.ml.model import SprintMLConfig, SprintMLModel


def train_baseline(
    trials_path: str | Path,
    output_dir: str | Path,
    n_estimators: int = 200,
    seed: int = 42,
    include_outliers: bool = False,
) -> Dict:
    """Train and persist the baseline sprint model.

    The dataset must contain athlete-level ``split`` values. A trial from an
    athlete in one split can never appear in another split, which prevents
    athlete-level leakage between train and test data.
    """
    trials_file = Path(trials_path)
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)

    data = pd.read_csv(trials_file)
    required = set(DEFAULT_FEATURE_COLUMNS) | {"time_10m_s", "split", "athlete_id", "trial_id"}
    missing = sorted(required - set(data.columns))
    if missing:
        raise ValueError(f"Missing required columns: {', '.join(missing)}")
    if "quality_flag" in data.columns and not include_outliers:
        data = data[data["quality_flag"] == "ok"].copy()
    data = data.dropna(subset=DEFAULT_FEATURE_COLUMNS + ["time_10m_s"]).copy()
    if data.empty:
        raise ValueError("No valid trial rows remain after filtering")

    config = SprintMLConfig(
        n_estimators=n_estimators,
        random_state=seed,
    )
    model = SprintMLModel(config=config)
    model.fit(data, include_outliers=include_outliers)

    test = data[data["split"] == config.test_split].copy().reset_index(drop=True)
    predictions = model.predict(test).reset_index(drop=True)
    importance = model.feature_importances()
    importance.to_csv(output_path / "feature_importance.csv", index=False)

    prediction_rows = []
    for index, (_, row) in enumerate(test.iterrows()):
        prediction = {
            "trial_id": row["trial_id"],
            "athlete_id": row["athlete_id"],
            "split": row["split"],
            "actual_time_10m_s": float(row["time_10m_s"]),
            "predicted_time_10m_s": float(predictions.loc[index, "predicted_time_10m_s"]),
        }
        if "predicted_quality_class" in predictions.columns:
            prediction["actual_quality_class"] = str(row.get("quality_class", ""))
            prediction["predicted_quality_class"] = str(predictions.loc[index, "predicted_quality_class"])
        prediction_rows.append(prediction)
    pd.DataFrame(prediction_rows).to_csv(output_path / "test_predictions.csv", index=False)

    metrics = dict(model.metrics)
    metrics.update({
        "seed": seed,
        "n_estimators": n_estimators,
        "include_outliers": include_outliers,
        "dataset_file": str(trials_file),
        "rows": {
            **metrics["rows"],
            "validation": int((data["split"] == "val").sum()),
        },
        "athletes": {
            **metrics["athletes"],
            "validation": int(data.loc[data["split"] == "val", "athlete_id"].nunique()),
        },
        "artifacts": {
            "model": str(output_path / "model.joblib"),
            "feature_importance": str(output_path / "feature_importance.csv"),
            "predictions": str(output_path / "test_predictions.csv"),
        },
    })
    (output_path / "metrics.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    model.save(output_path / "model.joblib")
    return metrics


def load_model(model_path: str | Path) -> SprintMLModel:
    """Load a model bundle generated by :func:`train_baseline`."""
    return SprintMLModel.load(model_path)
